/**
 * `npm run library`: writes src/content/<lang>/library.ts, the index of the long texts in src/content/<lang>/long/.
 * `npm run library -- --check` only reports whether an index is out of date (the validator runs this check too).
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { textInfo } from '../src/content/index';
import type { LangId, Text } from '../src/content/types';
import { LANG_IDS } from '../src/core/langs';

const ROOT = fileURLToPath(new URL('../src/content/', import.meta.url));

/** The long texts of a language in file order (or just the one with this id). */
export async function longTexts(lang: LangId, id?: string): Promise<Text[]> {
  const dir = `${ROOT}${lang}/long/`;
  if (!existsSync(dir)) return [];
  const files = readdirSync(dir).filter((f) => f.endsWith('.ts') && (!id || f === `${id}.ts`)).sort();
  return Promise.all(files.map(async (f) => (await import(pathToFileURL(dir + f).href)).default as Text));
}

/** The library.ts source for a language. */
export async function librarySource(lang: LangId): Promise<string> {
  const infos = (await longTexts(lang)).map((t) => textInfo(t, true)).sort((a, b) => a.lv - b.lv || a.words - b.words);
  const rows = infos.map((i) => `  ${JSON.stringify(i)},`).join('\n');
  return `// Generated by \`npm run library\` from the files in long/. Do not edit.\nimport type { TextInfo } from '../types';\n\nconst library: TextInfo[] = [\n${rows}${rows ? '\n' : ''}];\n\nexport default library;\n`;
}

/** Languages whose library.ts does not match their long/ folder. */
export async function staleLibraries(): Promise<LangId[]> {
  const out: LangId[] = [];
  for (const l of LANG_IDS) {
    const path = `${ROOT}${l}/library.ts`;
    if (!existsSync(path) || readFileSync(path, 'utf8') !== (await librarySource(l))) out.push(l);
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    const stale = await staleLibraries();
    console.log(stale.length ? `Out of date: ${stale.join(', ')}. Run npm run library.` : 'Libraries up to date.');
    process.exit(stale.length ? 1 : 0);
  }
  for (const l of LANG_IDS) {
    const src = await librarySource(l);
    writeFileSync(`${ROOT}${l}/library.ts`, src);
    console.log(`${l}: ${(src.match(/^ {2}\{/gm) || []).length} long texts`);
  }
}
